#!/usr/bin/env python3
# generator
from pathlib import Path
import logging
import re

from waftocmake.generators.common import cm_quoted, emit_conditional, INDENT

CMAKE_Minimum_Required = "3.27"

class bcolors:
    HEADER = '\033[95m'
    OKBLUE = '\033[94m'
    OKCYAN = '\033[96m'
    OKGREEN = '\033[92m'
    WARNING = '\033[93m'
    FAIL = '\033[91m'
    ENDC = '\033[0m'
    BOLD = '\033[1m'
    UNDERLINE = '\033[4m'

logger = logging.getLogger(__name__)

PLATFORM_BLOCK = '''\
# ---- target platform (replacement for conf.env.DEST_OS / DEST_CPU) ----
if(WIN32)
    set(WAF_DEST_OS win32)
elseif(APPLE)
    set(WAF_DEST_OS darwin)
elseif(ANDROID)
    set(WAF_DEST_OS android)
elseif(CMAKE_SYSTEM_NAME STREQUAL "Linux")
    set(WAF_DEST_OS linux)
else()
    string(TOLOWER "${CMAKE_SYSTEM_NAME}" WAF_DEST_OS)
endif()

set(ARCH_X86 OFF)
set(ARCH_X86_64 OFF)
set(ARCH_ARM OFF)
set(ARCH_AARCH64 OFF)
string(TOLOWER "${CMAKE_SYSTEM_PROCESSOR}" _waf_proc)
if(_waf_proc MATCHES "^(aarch64|arm64)")
    set(ARCH_AARCH64 ON)
    set(WAF_DEST_CPU aarch64)
elseif(_waf_proc MATCHES "^arm")
    set(ARCH_ARM ON)
    set(WAF_DEST_CPU arm)
elseif(CMAKE_SIZEOF_VOID_P EQUAL 8)
    set(ARCH_X86_64 ON)
    set(WAF_DEST_CPU x86_64)
else()
    set(ARCH_X86 ON)
    set(WAF_DEST_CPU x86)
endif()

if(CMAKE_SIZEOF_VOID_P EQUAL 8)
    set(ARCH_64BIT ON)
    set(ARCH_32BIT OFF)
else()
    set(ARCH_64BIT OFF)
    set(ARCH_32BIT ON)
endif()

# compatibility with CMakeLists generated by older waf2cmake versions
set(AMD64 ${ARCH_X86_64})

if(NOT CMAKE_BUILD_TYPE AND NOT CMAKE_CONFIGURATION_TYPES)
    set(CMAKE_BUILD_TYPE Release CACHE STRING "Build type" FORCE)
endif()

'''

GIT_BLOCK = '''\
# ---- git revision (replacement for the waf 'gitversion' tool) ----
set(GIT_VERSION "unknown")
find_package(Git QUIET)
if(GIT_FOUND)
    execute_process(
        COMMAND "${GIT_EXECUTABLE}" rev-parse --short HEAD
        WORKING_DIRECTORY "${CMAKE_SOURCE_DIR}"
        OUTPUT_VARIABLE _waf_git_out
        RESULT_VARIABLE _waf_git_res
        OUTPUT_STRIP_TRAILING_WHITESPACE
        ERROR_QUIET)
    if(_waf_git_res EQUAL 0 AND _waf_git_out)
        set(GIT_VERSION "${_waf_git_out}")
    endif()
endif()

'''


def render_option(o):
    help_text = cm_quoted(o.help)
    lines = []
    if o.flags:
        lines.append(f"# waf: {', '.join(o.flags)}")

    if o.kind == "string":
        lines.append(f"set({o.dest} {cm_quoted(o.default)} CACHE STRING {help_text})")
    elif o.default_cond:
        lines += [
            f"if({o.default_cond})",
            f"{INDENT}set(_{o.dest}_DEFAULT ON)",
            "else()",
            f"{INDENT}set(_{o.dest}_DEFAULT OFF)",
            "endif()",
            f"option({o.dest} {help_text} ${{_{o.dest}_DEFAULT}})",
        ]
    else:
        lines.append(f"option({o.dest} {help_text} {o.default})")
    return lines


def render_directive(d):
    k = d.kind

    if k == "define":
        return [f"add_compile_definitions({cm_quoted(d.value)})"]
    if k == "flag":
        return [f"add_compile_options({cm_quoted(d.value)})"]
    if k == "cflag":
        return [f"add_compile_options({cm_quoted('$<$<COMPILE_LANGUAGE:C>:' + d.value + '>')})"]
    if k == "cxxflag":
        return [f"add_compile_options({cm_quoted('$<$<COMPILE_LANGUAGE:CXX>:' + d.value + '>')})"]
    if k in ("cflag_opt", "cxxflag_opt"):
        lang = "C" if k == "cflag_opt" else "CXX"
        var = "WAF_HAS_" + lang + "_" + re.sub(r"[^A-Za-z0-9]", "_", d.value)
        return [
            f"check_compiler_flag({lang} {cm_quoted(d.value)} {var})",
            f"if({var})",
            f"{INDENT}add_compile_options({cm_quoted('$<$<COMPILE_LANGUAGE:' + lang + '>:' + d.value + '>')})",
            "endif()",
        ]
    if k == "linkflag":
        return [f"add_link_options({cm_quoted(d.value)})"]
    if k == "include":
        return [f"include_directories({cm_quoted(d.value)})"]
    if k == "set":
        return [f"set({d.value} {d.args[0]})"]
    if k == "set_expr":
        return [
            f"if({d.args[0]})",
            f"{INDENT}set({d.value} ON)",
            "else()",
            f"{INDENT}set({d.value} OFF)",
            "endif()",
        ]
    if k == "raw":
        return list(d.args)

    if k == "pkg":
        store, mandatory = d.args
        req = "REQUIRED" if mandatory else "QUIET"
        return [
            f"pkg_check_modules({store} {req} IMPORTED_TARGET {d.value})",
            f"set({store}_LIBRARY PkgConfig::{store})",
        ]

    if k == "lib":
        store, mandatory, framework = d.args
        var = f"{store}_LIBRARY"
        if framework:
            return [f'set({var} "-framework {d.value}")']
        if mandatory:
            return [f"set({var} {d.value})"]
        return [
            f"find_library({var} NAMES {d.value})",
            f"if(NOT {var})",
            f'{INDENT}set({var} "")',
            "endif()",
        ]

    raise RuntimeError(f"unknown directive {k}")


class _Sub:
    def __init__(self, path, conditions, exists):
        self.path = path
        self.conditions = conditions
        self.exists = exists


def write_rootproject(outfile, name, info, root: Path, version=None):
    """info: waftocmake.rootparser.RootInfo"""
    outfile = Path(outfile)
    outfile.parent.mkdir(parents=True, exist_ok=True)

    print(f"{bcolors.OKBLUE}Writing root project '{name}'{bcolors.ENDC}")
    logger.info(f" Writing root project '{name}'")

    version = version or info.version
    missing = []

    with open(outfile, "w", encoding="utf-8", newline="\n") as f:
        f.write("# ------------------------------------------------- #\n")
        f.write("# waf2cmake automatically generated root CMakeLists.txt,\n")
        f.write("# generated from the root wscript. Fix if needed before using.\n")
        f.write("# ------------------------------------------------- #\n\n")

        f.write(f"cmake_minimum_required(VERSION {CMAKE_Minimum_Required})\n\n")
        ver = f" VERSION {version}" if version else ""
        f.write(f"project({name}{ver} LANGUAGES C CXX)\n\n")

        f.write(PLATFORM_BLOCK)

        if info.needs_git:
            f.write(GIT_BLOCK)

        if info.needs_flag_checks:
            f.write("include(CheckCompilerFlag)\n\n")

        if info.needs_pkgconfig:
            f.write("find_package(PkgConfig QUIET)\n\n")

        if info.options:
            f.write("# ---- options (waf: options()) ----\n")
            for o in info.options:
                for line in render_option(o):
                    f.write(line + "\n")
            f.write("\n")

        if info.directives:
            f.write("# ---- configuration (waf: define_platform() / configure() / check_deps()) ----\n")
            emit_conditional(f, info.directives, lambda d: render_directive(d))
            f.write("\n")

        # ---- subprojects
        f.write("# ---- subprojects (waf: conf.add_subproject(projects[...])) ----\n")
        subs = []
        for conds, set_name in info.selections:
            for item, item_conds in info.set_items(set_name):
                # item conditions are relative to configure() top level, selection conditions come first
                subs.append(_Sub(item, tuple(conds) + tuple(item_conds), (root / item / "wscript").is_file()))

        def render_sub(s):
            if s.exists:
                print(f"{bcolors.OKCYAN}{s.path}{bcolors.ENDC}", end=" ")
                logger.info(s.path)
                return [f"add_subdirectory({s.path})"]
            if s.path not in missing:
                missing.append(s.path)
            return [f"# add_subdirectory({s.path})  # TODO: no wscript found, not converted"]

        emit_conditional(f, subs, render_sub)
        print()

    if missing:
        logger.warning("no wscript for: %s", ", ".join(missing))
    return missing
